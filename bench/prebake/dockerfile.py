"""Dockerfiles that replay a recorded Harbor install FROM the task image.

Each rule keeps a pre-baked container the same as a stock one:

- ARG BASE / FROM ${BASE}: the build is given the exact local task image.
- One exec-form RUN per recorded exec, ["bash", "-c", cmd], or
  ["env", "K=V", ..., "bash", "-c", cmd] where Harbor passes per-exec env
  (`docker exec -e`). The strings are byte-identical to Harbor's, including
  the "set -o pipefail; " its installed agents add. The exec form runs
  `bash -c` the way Harbor's exec does, without a SHELL line.
- COPY --chmod=755 for uploads: docker cp from a Windows host gives 755.
- Nothing else. No ENV, USER, WORKDIR, SHELL, CMD or ENTRYPOINT, so the image
  config stays the task image's; no LABEL (labels go on the build as
  --label); no apt cleanup, --no-install-recommends or cache deletion, which a
  stock trial does not do either; no syntax directive, which would pull a
  frontend image. RUNs execute in the image's WORKDIR as root, as Harbor's
  exec does on every baked image (the recorder refuses others).
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from ..environments.prebaked import BAKE_FORMAT, harbor_version
from .recorder import RecipeError, Recording, Step, Upload

__all__ = ["BAKE_FORMAT", "FORBIDDEN_INSTRUCTIONS", "check", "render"]

FORBIDDEN_INSTRUCTIONS = ("ADD", "CMD", "ENTRYPOINT", "ENV", "EXPOSE", "HEALTHCHECK", "LABEL", "MAINTAINER",
                          "ONBUILD", "SHELL", "STOPSIGNAL", "USER", "VOLUME", "WORKDIR")
_ALLOWED = ("ARG", "FROM", "RUN", "COPY")
_DIRECTIVE = re.compile(r"#\s*(syntax|escape|check)\s*=", re.I)
_CONTEXT_NAME = re.compile(r"[A-Za-z0-9._-]+")


def check(text: str) -> list[str]:
    """Why text breaks the rules above; [] when it keeps them."""
    problems = []
    for n, line in enumerate(text.splitlines(), 1):
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("#"):
            if _DIRECTIVE.match(stripped):
                problems.append(f"line {n}: a parser directive")
            continue
        word = stripped.split(None, 1)[0].upper()
        if word in FORBIDDEN_INSTRUCTIONS:
            problems.append(f"line {n}: {word} is never emitted")
        elif word not in _ALLOWED:
            problems.append(f"line {n}: unexpected instruction {word}")
    return problems


def _secret_free(text: str) -> bool:
    from ..extract import redact

    return redact(text) == text


def _run_line(step: Step) -> str:
    if step.user not in (None, "root", "0"):
        raise RecipeError(f"an install step runs as user {step.user!r}")
    if step.cwd:
        raise RecipeError(f"an install step runs in {step.cwd}, which RUN cannot do without WORKDIR")
    env = [f"{k}={v}" for k, v in step.env.items()]
    if not all(_secret_free(x) for x in [step.command, *env]):
        raise RecipeError("an install step carries a credential-like value; it is never written to a Dockerfile")
    argv = ["env", *env, "bash", "-c", step.command] if env else ["bash", "-c", step.command]
    return "RUN " + json.dumps(argv)


def render(recording: Recording) -> tuple[str, dict[str, Path]]:
    """(Dockerfile text, build context): the context maps each name the text
    COPYs from to the host file or folder the agent's install() staged."""
    lines = [f"# Pre-baked {recording.family} {recording.version} ({recording.variant}): Harbor "
             f"{harbor_version()}'s own setup() execs for this task image,",
             "# one RUN each, byte for byte. Generated by bench.prebake; build with --build-arg BASE=<task image>.",
             "ARG BASE",
             "FROM ${BASE}"]
    context: dict[str, Path] = {}
    for step in recording.install_steps:
        if isinstance(step, Upload):
            name = step.source.name
            if not _CONTEXT_NAME.fullmatch(name) or name in context:
                name = f"upload-{len(context) + 1}"
            context[name] = step.source
            slash = "/" if step.is_dir else ""
            if re.search(r"\s", step.target):
                lines.append(f"COPY --chmod=755 {json.dumps([name + slash, step.target.rstrip('/') + slash])}")
            else:
                lines.append(f"COPY --chmod=755 {name}{slash} {step.target.rstrip('/')}{slash}")
        else:
            lines.append(_run_line(step))
    text = "\n".join(lines) + "\n"
    problems = check(text)
    if problems:
        raise RecipeError("the Dockerfile would break the bake rules: " + "; ".join(problems))
    return text, context
